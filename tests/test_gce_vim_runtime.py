@pytest.mark.parametrize('method', ['vim'])
def test_real_estimator_update_with_different_context_and_target_width(method):
    spec = EnvironmentConfig('ant_soccer',42,8,1.,400,3,3,.99,2)
    cfg = EstimatorConfig(hidden_dim=16, scalar_hidden_dim=8, hidden_layers=1)
    key = jax.random.PRNGKey(7)
    obs = jax.random.normal(key, (4,42))
    targets = obs[:,:2]+.1
    source, source_state, decoder, decoder_state = create_vim_train_states(key,key,spec,cfg)
    actions, latent, log_h = source.apply({'params':source_state.params},obs,key,method=source.sample)
    replay_h, _ = source.apply({'params':source_state.params},obs,actions,latent)
    np.testing.assert_allclose(log_h,replay_h,rtol=1e-5,atol=1e-5)
    batch = ProbeBatch(obs,actions,latent,targets)
    updated, metrics = jax.jit(make_vim_train_step(source,decoder))(
        (source_state,decoder_state),batch,jnp.ones(4))
    assert all(int(state.step)==1 for state in updated)
    # Saturated tanh rounds to +/-1; likelihood must remain finite without atanh.
    latent = jnp.full_like(latent, 20.)
    saturated = jnp.tanh(latent)
    log_q = decoder.apply({'params':updated[1].params},obs,targets,saturated,latent)
    assert np.isfinite(np.asarray(log_q)).all()
    assert np.isfinite(np.asarray(metrics)).all()


@pytest.mark.skipif(os.environ.get('GCE_VIM_WARP_TEST')!='1',reason='explicit real-GPU Warp gate')
def test_real_warp_collection_and_checkpoint(tmp_path, monkeypatch):
    from empowerment_warp.training.baselines.recipe import Recipe
    from empowerment_warp.training.baselines.runner import build, update, make_benchmark_environment
    from empowerment_warp.training.baselines.collector import select_lanes
    from empowerment_warp.agents.see_sac import ContinuousSAC
    from empowerment_warp.agents.skill_classifier import SkillLearner
    from empowerment_warp.checkpointing import CheckpointStore
    def reject_skill_or_sac_construction(*args, **kwargs):
        pytest.fail('standalone VIM/GCE must not construct SAC or a skill learner')
    monkeypatch.setattr(ContinuousSAC, '__init__', reject_skill_or_sac_construction)
    monkeypatch.setattr(SkillLearner, '__init__', reject_skill_or_sac_construction)
    assert jax.devices()[0].platform == 'gpu'
    print('GPU:',jax.devices()[0].device_kind,flush=True)
    recipe = Recipe(os.environ.get('GCE_VIM_ENV','ant_soccer'),os.environ.get('GCE_VIM_METHOD','gce_vector'),
                    3,100000,str(tmp_path),num_envs=4,rollout_steps=4,
                    episode_steps=4,estimator=EstimatorConfig(hidden_dim=16,scalar_hidden_dim=8,
                        hidden_layers=1,buffer_size=8,batch_size=4,replay_passes=1))
    env = make_benchmark_environment(recipe)
    keys = jax.random.split(jax.random.PRNGKey(2),4)
    initial = env.reset(keys)
    other = env.step(initial,jnp.ones((4,env.action_size))*.1)
    mask = jnp.array([True,False,True,False])
    selected = jax.jit(select_lanes)(mask,initial,other)
    from mujoco.mjx._src.types import tree_path_to_attr_str
    from mujoco.mjx.warp.types import _BATCH_DIM
    # Warp explicitly leaves global contact/scratch arrays unmerged in Data.where.
    # Check every per-world data field, not global buffers regenerated by step().
    selected_leaves = jax.tree_util.tree_flatten_with_path(selected.data)[0]
    for (path,actual), old, new in zip(selected_leaves,jax.tree.leaves(initial.data),
                                     jax.tree.leaves(other.data),strict=True):
        if _BATCH_DIM['Data'].get(tree_path_to_attr_str(path),True):
            shape = (4,)+(1,)*(old.ndim-1)
            np.testing.assert_array_equal(actual,np.where(np.asarray(mask).reshape(shape),new,old))
    action = jnp.ones((4,env.action_size))*.2
    next_selected = env.step(selected,action)
    expected = select_lanes(mask,env.step(initial,action),env.step(other,action))
    # Contact/constraint rows may permute when worlds are combined. Compare the
    # full integration state (including warm starts and applied controls/forces),
    # not the row ordering of regenerated solver workspaces.
    for field in ('time','qpos','qvel','act','qacc_warmstart','ctrl','qfrc_applied',
                  'xfrc_applied','eq_active','mocap_pos','mocap_quat','userdata'):
        # Mixed-world contact ordering produced a measured 4.6e-5 warm-start
        # difference. Position/velocity/control tolerances remain unchanged.
        atol = 1e-4 if field == 'qacc_warmstart' else 1e-5
        np.testing.assert_allclose(getattr(next_selected.data,field),getattr(expected.data,field),
                                   rtol=1e-5,atol=atol,err_msg=field)
    for actual,reference in zip(jax.tree.leaves(next_selected._replace(data=None)),
                                jax.tree.leaves(expected._replace(data=None)),strict=True):
        np.testing.assert_allclose(actual,reference,rtol=1e-5,atol=1e-5)
    state, functions = build(recipe,env)
    assert set(state) == {'estimator', 'ppo', 'controller', 'buffer', 'update', 'rng'}
    initial_policy = state['ppo'].params
    collected, _, rollout, _, exploration = functions['collect'](
        state['ppo'], state['controller'], state['rng']['controller'])
    assert np.asarray(rollout.dones[-1]).all()
    assert not np.asarray(rollout.terminated).any()
    assert int(exploration['completed_episodes']) == 4
    assert not np.array_equal(rollout.terminal_observations[-1], collected.observation)
    assert np.asarray(collected.coverage_grids).sum() > 0
    row = update(recipe,state,functions)
    assert row['controller_steps']==16 and row['probe_steps']==12 and row['replay_count']==4
    assert row['exploration/completed_episodes'] == 4
    assert any(k.startswith('exploration/cells_visited_') and row[k] > 0 for k in row)
    assert all(np.isfinite(value) for value in row.values())
    assert any(not np.array_equal(a, b) for a, b in zip(
        jax.tree.leaves(initial_policy), jax.tree.leaves(state['ppo'].params), strict=True))
    store = CheckpointStore(tmp_path/'checkpoints')
    store.save(28,state,recipe.resolved())
    fresh_state, _ = build(recipe,env)
    restored = store.restore(fresh_state)
    for actual, reference in zip(jax.tree.leaves(restored),jax.tree.leaves(state),strict=True):
        np.testing.assert_array_equal(actual,reference)
    before = functions['evaluations']['deterministic'](state['ppo'].params)
    after = functions['evaluations']['deterministic'](restored['ppo'].params)
    for actual, reference in zip(jax.tree.leaves(after),jax.tree.leaves(before),strict=True):
        # Checkpoint leaves above are bit-exact. GPU contact trajectories can
        # differ by roundoff even under identical deterministic policy weights.
        np.testing.assert_allclose(actual,reference,rtol=1e-6,atol=1e-6)


def test_vim_controller_floor_keeps_source_objective_raw():
    from empowerment_warp.agents.vim import empowerment_from_observations
    from flax.traverse_util import flatten_dict, unflatten_dict
    spec = EnvironmentConfig('ant_soccer',42,8,1.,400,3,3,.99,2)
    cfg = EstimatorConfig(hidden_dim=16, scalar_hidden_dim=8, hidden_layers=1)
    key = jax.random.PRNGKey(7)
    source, state, _, _ = create_vim_train_states(key, key, spec, cfg)
    flat = flatten_dict(jax.tree.map(jnp.zeros_like, state.params))
    biases = [p for p in flat if 'value_network' in p and p[-1] == 'bias' and flat[p].shape == (1,)]
    assert len(biases) == 1
    flat[biases[0]] = jnp.array([-2.])
    params = unflatten_dict(flat)
    obs = jnp.zeros((4, 42))
    raw = source.apply({'params': params}, obs, 1., method=source.empowerment)
    np.testing.assert_array_equal(raw, -2.)
    np.testing.assert_array_equal(empowerment_from_observations(source, params, obs, beta=1.), 0.)
